#[test]
fn kat_encrypt_matches_reference() {
    for v in VECTORS {
        let mut ct = [0u8; 64];
        let mut tag = [0u8; 16];
        let ct = &mut ct[..v.pt.len()];
        ascon_aead_encrypt(&KEY, &NONCE, v.ad, v.pt, ct, &mut tag);
        assert_eq!(ct, v.ct, "ciphertext mismatch on KAT `{}`", v.name);
        assert_eq!(&tag, &v.tag, "tag mismatch on KAT `{}`", v.name);
    }
}

#[test]
fn kat_decrypt_recovers_plaintext() {
    for v in VECTORS {
        let mut pt = [0u8; 64];
        let pt = &mut pt[..v.ct.len()];
        let ok = ascon_aead_decrypt(&KEY, &NONCE, v.ad, v.ct, pt, &v.tag);
        assert!(ok, "auth failed on KAT `{}`", v.name);
        assert_eq!(pt, v.pt, "plaintext mismatch on KAT `{}`", v.name);
    }
}

#[test]
fn kat_decrypt_rejects_tampered_tag() {
    for v in VECTORS {
        let mut bad = v.tag;
        bad[0] ^= 0x01;
        let mut pt = [0u8; 64];
        let pt = &mut pt[..v.ct.len()];
        let ok = ascon_aead_decrypt(&KEY, &NONCE, v.ad, v.ct, pt, &bad);
        assert!(!ok, "tampered tag accepted on KAT `{}`", v.name);
        assert!(pt.iter().all(|&b| b == 0), "buffer not zeroized on `{}`", v.name);
    }
}

